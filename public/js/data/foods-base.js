/** Minuscolo, senza accenti e senza apostrofi: la ricerca ignora la forma. */
export function normalize(text) {
  return String(text)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/['’`]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Elenco piatto, nella forma usata dal resto dell'app. */
export const BASE_FOODS = Object.entries(TABLE).flatMap(([category, rows]) =>
  rows.map(([name, kcal, protein, carbs, fat, servingG]) => ({
    code: '',
    name,
    brand: category,
    quantity: '',
    servingG: servingG || null,
    image: '',
    source: 'base',
    category,
    per100: { kcal, protein, carbs, fat },
    // campo di ricerca precalcolato: nome + categoria + sinonimi
    haystack: normalize(`${name} ${category} ${ALIASES[name] || ''}`)
  }))
);

/** Indice per nome esatto: lo usano le ricette per risolvere gli ingredienti. */
const BY_NAME = new Map(BASE_FOODS.map((f) => [normalize(f.name), f]));

export function findBaseFood(name) {
  return BY_NAME.get(normalize(name)) || null;
}

/**
 * Ricerca negli alimenti base. Ordina per: inizia-con, poi parola intera,
 * poi contiene — così "pol" mette "Petto di pollo" prima di "Pollo alla ...".
 */
export function searchBaseFoods(query, limit = 30) {
  const q = normalize(query);
  if (q.length < 2) return [];
  const words = q.split(' ').filter(Boolean);
  const escaped = q.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const wordStart = new RegExp(`\\b${escaped}`);

  return BASE_FOODS.map((food) => {
    if (!words.every((w) => food.haystack.includes(w))) return null;
    const name = normalize(food.name);
    let score = 3;
    if (name.startsWith(q)) score = 0;
    else if (wordStart.test(name)) score = 1;
    else if (name.includes(q)) score = 2;
    return { food, score, len: food.name.length };
  })
    .filter(Boolean)
    .sort((a, b) => a.score - b.score || a.len - b.len)
    .slice(0, limit)
    .map((x) => x.food);
}

